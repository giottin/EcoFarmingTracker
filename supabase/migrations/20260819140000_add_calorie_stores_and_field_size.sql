create policy "members can update calorie store foods" on public.calorie_store_foods for update to anon using ((select private.has_workspace_access())) with check ((select private.has_workspace_access()));
create policy "members can delete calorie store foods" on public.calorie_store_foods for delete to anon using ((select private.has_workspace_access()));
